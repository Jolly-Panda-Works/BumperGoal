const LANG_KEY = 'flickkick.adminLang.v1';
const isAdminLang = (v: unknown): v is AdminLang => v === 'en' || v === 'fa' || v === 'ar';

function initialLang(): AdminLang {
  const saved = readJson<string>(LANG_KEY);
  if (isAdminLang(saved)) return saved;
  const game = settingsStore.get().language;
  return isAdminLang(game) ? game : 'en';
}

let lang: AdminLang = initialLang();
const listeners = new Set<() => void>();

export function setAdminLang(next: AdminLang): void {
  lang = next;
  writeJson(LANG_KEY, next);
  listeners.forEach((l) => l());
}

export function useAdminLang(): AdminLang {
  return useSyncExternalStore(
    (l) => {
      listeners.add(l);
      return () => listeners.delete(l);
    },
    () => lang,
  );
}

export const adminDir = (): 'ltr' | 'rtl' => (lang === 'en' ? 'ltr' : 'rtl');

/** Panel text in the current panel language; {name} placeholders are filled from vars. */
export function tr(key: AdminKey, vars: Record<string, string | number> = {}): string {
  const text = DICTS[lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Label of a config field or path segment in the panel language. */
export function fieldLabel(key: string): string {
  if (key.startsWith('@') || /^\d+$/.test(key)) return key.replace(/^@/, '');
  const local = lang !== 'en' ? FIELDS[key]?.[lang] : undefined;
  return local ?? key.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase());
}

/** Numbers in the panel language's digits. */
export function num(n: number): string {
  try {
    return new Intl.NumberFormat(lang === 'en' ? 'en-US' : lang === 'fa' ? 'fa-IR' : 'ar').format(n);
  } catch {
    return String(n);
  }
}

/** Tooltip for a config field in the panel language, if there is one. */
export function fieldHelp(key: string): string | undefined {
  return FIELD_HELP[key]?.[lang];
}
